const LYCEE_ORDER = ['Seconde_LVAB','Seconde_LVC','Première_LVAB','Première_LVC','Terminale_LVAB','Terminale_LVC','Première_AMC','Terminale_AMC','Première_LLCER','Terminale_LLCER'];

// Aplati toutes les listes lycée en une seule (dédupliquée, ordre conservé).
// Utilisé par la checkbox "Tous niveaux" du référentiel grammaire/phonologie.
const flattenAll = (db) => {
  const seen = new Set();
  const out = [];
  for (const k of LYCEE_ORDER) {
    for (const item of (db[k] || [])) {
      if (!seen.has(item)) { seen.add(item); out.push(item); }
    }
  }
  return out;
};

export const getAllGrammar = () => flattenAll(GRAMMAR_BO);
export const getAllPhono = () => flattenAll(PHONO_BO);

// Récupère le bon set de descripteurs selon niveau lycée + LVA/B vs LVC
export const getGrammarFor = (niveau, lv, allLevels = false) => {
  if (allLevels) return getAllGrammar();
  // niveau peut être Seconde / Première / Terminale (TC) ou avec _AMC / _LLCER
  if (/_AMC$|_LLCER$/.test(niveau)) return GRAMMAR_BO[niveau] || [];
  const key = `${niveau}_${lv || 'LVAB'}`;
  return GRAMMAR_BO[key] || [];
};

export const getPhonoFor = (niveau, lv, allLevels = false) => {
  if (allLevels) return getAllPhono();
  if (/_AMC$|_LLCER$/.test(niveau)) return PHONO_BO[niveau] || [];
  const key = `${niveau}_${lv || 'LVAB'}`;
  return PHONO_BO[key] || [];
};
